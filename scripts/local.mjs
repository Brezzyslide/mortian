#!/usr/bin/env node
/**
 * Run the whole platform on this computer, with sandbox providers (no real SMS, payments or
 * AWS). Commands:
 *   pnpm local:setup   one-time: .env with fresh secrets, database, build, admin login, test data
 *   pnpm local         start the API and the three web apps
 *   pnpm local:daily   run the nightly job now (arrears, notices, weekly payouts)
 *   pnpm local:test    run every check CI runs (build, typecheck, tests, synth) in a separate test database
 *   pnpm local:reset   delete the local database and start again (asks first)
 * Uses Docker for Postgres unless DATABASE_URL in .env points somewhere else.
 */
import { execSync, spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const envFile = join(root, '.env');
const PORTS = { api: 3000, web: 5173, console: 5174, sign: 5175 };
const cmd = process.argv[2] ?? 'start';

const say = (s) => console.log(`\n▸ ${s}`);
const fail = (s) => {
  console.error(`\n✖ ${s}`);
  process.exit(1);
};
const run = (c, env = {}) => {
  try {
    execSync(c, { cwd: root, stdio: 'inherit', env: { ...process.env, ...env } });
  } catch {
    fail(`This step failed: ${c}\n  The error is printed just above. Paste it if you are stuck.`);
  }
};
/** Prompts that work typed or piped: readline buffers piped lines before questions are asked. */
async function ask(questions) {
  const rl = createInterface({ input: process.stdin, terminal: process.stdin.isTTY });
  const lines = rl[Symbol.asyncIterator]();
  const answers = [];
  for (const q of questions) {
    process.stdout.write(q);
    const { value, done } = await lines.next();
    if (done) fail('No answer given.');
    answers.push(value.trim());
  }
  rl.close();
  return answers;
}
const has = (c) => {
  try {
    execSync(c, { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};

let composeCmd;
/** `docker compose` (plugin) or the older standalone `docker-compose`. */
function compose() {
  if (composeCmd) return composeCmd;
  if (has('docker compose version')) composeCmd = 'docker compose';
  else if (has('docker-compose version')) composeCmd = 'docker-compose';
  else
    fail(
      'Docker Compose is missing. With Docker Desktop: quit and reopen it, or reinstall from docker.com. ' +
        'With Homebrew: brew install docker-compose. Then check with:  docker compose version',
    );
  return composeCmd;
}

function readEnv() {
  if (!existsSync(envFile)) return {};
  return Object.fromEntries(
    readFileSync(envFile, 'utf8')
      .split('\n')
      .filter((l) => l.trim() && !l.trim().startsWith('#') && l.includes('='))
      .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
  );
}

function writeEnvIfMissing() {
  if (existsSync(envFile)) {
    say('.env already exists: keeping it (delete it to generate new secrets).');
    return;
  }
  const b64 = () => randomBytes(32).toString('base64');
  writeFileSync(
    envFile,
    `# Local only. Generated by scripts/local.mjs. Never commit this file.
APP_ENV=development
DATABASE_URL=postgres://postgres:postgres@localhost:5432/project_dev
MIGRATE_ON_BOOT=true
PORT=${PORTS.api}
AUTH_JWT_SECRET=${b64()}
AUTH_OTP_PEPPER=${b64()}
AUTH_FIELD_KEY=${b64()}
MESSAGING_PROVIDER=sandbox
COLLECTIONS_PROVIDER=sandbox
COLLECTIONS_WEBHOOK_SECRET=${randomBytes(32).toString('hex')}
SIGNING_BASE_URL=http://localhost:${PORTS.sign}/sign/
LOCAL_DOCUMENTS_DIR=${join(root, '.local-data', 'documents')}
`,
    { mode: 0o600 },
  );
  say('Wrote .env with fresh random secrets.');
}

function usesDocker(env) {
  return (env.DATABASE_URL ?? '').includes('@localhost:5432/project_dev');
}

async function waitForDb() {
  for (let i = 0; i < 30; i++) {
    if (has(`${compose()} exec -T db pg_isready -U postgres`)) return;
    await new Promise((r) => setTimeout(r, 1000));
  }
  fail('The database did not start. Is Docker Desktop running?');
}

async function setup() {
  const major = Number(process.versions.node.split('.')[0]);
  if (major < 22) fail(`Node 22 or newer is needed (this is ${process.versions.node}). Install it from nodejs.org.`);
  writeEnvIfMissing();
  const env = readEnv();
  if (usesDocker(env)) {
    if (!has('docker info')) fail('Docker is not running. Start Docker Desktop and run this again.');
    say('Starting the database (Docker)…');
    run(`${compose()} up -d db`);
    await waitForDb();
  }
  say('Installing and building (a few minutes the first time)…');
  run('pnpm install');
  run('pnpm build');

  say('Creating the tables…');
  run('node apps/api/dist/cli/migrate.js', env);

  const admins = execSync(
    `node -e "const pg=require('pg');const p=new pg.Pool({connectionString:process.env.DATABASE_URL});p.query(\\"SELECT count(*)::int n FROM person_role WHERE role='super_admin'\\").then(r=>{console.log(r.rows[0].n);p.end()})"`,
    { cwd: join(root, 'apps/api'), env: { ...process.env, ...env } },
  )
    .toString()
    .trim();
  if (admins === '0') {
    say('Create your admin login for the console.');
    const [email, name, password] =
      process.env.ADMIN_EMAIL && process.env.ADMIN_NAME && process.env.ADMIN_PASSWORD
        ? [process.env.ADMIN_EMAIL, process.env.ADMIN_NAME, process.env.ADMIN_PASSWORD]
        : await ask(['  Email: ', '  Full name: ', '  Password (12+ characters, letters and digits): ']);
    run('node apps/api/dist/cli/create-admin.js', { ...env, ADMIN_EMAIL: email, ADMIN_NAME: name, ADMIN_PASSWORD: password });
  } else {
    say('An admin login already exists: skipping.');
  }

  say('Loading test data (placeholder tiers, contract, prices, payout rules)…');
  run('node apps/api/dist/cli/seed-local.js', env);
  say('Done. Start everything with:  pnpm local');
}

function start() {
  const env = readEnv();
  if (!env.DATABASE_URL) fail('No .env yet. Run:  pnpm local:setup');
  if (usesDocker(env)) {
    if (!has('docker info')) fail('Docker is not running. Start Docker Desktop and run this again.');
    run(`${compose()} up -d db`);
  }
  // Set LOCAL_NETWORK=1 to open the apps to phones on the same Wi-Fi.
  const host = process.env.LOCAL_NETWORK ? ['--host'] : [];
  const procs = [
    ['api', 'node', ['apps/api/dist/main.js']],
    ['web', 'pnpm', ['--filter', '@project/web', 'exec', 'vite', '--port', String(PORTS.web), '--strictPort', ...host]],
    ['console', 'pnpm', ['--filter', '@project/console', 'exec', 'vite', '--port', String(PORTS.console), '--strictPort', ...host]],
    ['sign', 'pnpm', ['--filter', '@project/sign', 'exec', 'vite', '--port', String(PORTS.sign), '--strictPort', ...host]],
  ];
  const children = procs.map(([name, bin, args]) => {
    const c = spawn(bin, args, { cwd: root, env: { ...process.env, ...env }, stdio: ['ignore', 'pipe', 'pipe'] });
    const tag = `[${name}]`.padEnd(10);
    const out = (d) => d.toString().split('\n').filter(Boolean).forEach((l) => console.log(`${tag}${l}`));
    c.stdout.on('data', out);
    c.stderr.on('data', out);
    c.on('exit', (code) => code && console.log(`${tag}stopped (exit ${code})`));
    return c;
  });
  const stop = () => {
    children.forEach((c) => c.kill());
    process.exit(0);
  };
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
  setTimeout(
    () =>
      console.log(`
  Customer app   http://localhost:${PORTS.web}/app/
  Staff console  http://localhost:${PORTS.console}/console/   (SMS codes: console → Sandbox SMS)
  Signing page   http://localhost:${PORTS.sign}/sign/          (opened from links in Sandbox SMS)
  API            http://localhost:${PORTS.api}/v1/health
  Ctrl+C stops everything. Data stays in the database between runs.
`),
    4000,
  );
}

/** The same checks as CI, against project_test so your local data is never touched. */
async function test() {
  const env = readEnv();
  const base = env.DATABASE_URL ?? 'postgres://postgres:postgres@localhost:5432/project_dev';
  if (!/\/project_dev(\?|$)/.test(base)) fail('local:test expects DATABASE_URL to end in /project_dev.');
  const testUrl = base.replace(/\/project_dev(\?|$)/, '/project_test$1');
  if (usesDocker(env) || !existsSync(envFile)) {
    if (!has('docker info')) fail('Docker is not running. Start Docker Desktop and run this again.');
    run(`${compose()} up -d db`);
    await waitForDb();
    if (!has(`${compose()} exec -T db psql -U postgres -tAc "SELECT 1 FROM pg_database WHERE datname='project_test'" | grep -q 1`)) {
      run(`${compose()} exec -T db psql -U postgres -c "CREATE DATABASE project_test"`);
    }
  }
  // Only the test database URL: the tests bring their own keys and must not see .env secrets.
  const testEnv = { DATABASE_URL: testUrl };
  for (const step of ['build', 'typecheck', 'test', 'synth']) {
    say(`pnpm ${step}…`);
    run(`pnpm ${step}`, testEnv);
  }
  say('All checks passed.');
}

async function reset() {
  const [a] = await ask(['Delete ALL local data (accounts, loans, deliveries) and start again? Type "reset": ']);
  if (a !== 'reset') fail('Not reset.');
  run(`${compose()} down -v`);
  rmSync(join(root, '.local-data'), { recursive: true, force: true });
  say('Local database deleted. Run:  pnpm local:setup');
}

if (cmd === 'setup') await setup();
else if (cmd === 'start') start();
else if (cmd === 'daily') run('node apps/api/dist/cli/daily-job.js', readEnv());
else if (cmd === 'test') await test();
else if (cmd === 'reset') await reset();
else fail(`Unknown command "${cmd}". Use setup, start, daily, test or reset.`);
