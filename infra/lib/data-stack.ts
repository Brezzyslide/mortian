import { Duration, RemovalPolicy, Stack, type StackProps } from 'aws-cdk-lib';
import * as ec2 from 'aws-cdk-lib/aws-ec2';
import type * as kms from 'aws-cdk-lib/aws-kms';
import * as rds from 'aws-cdk-lib/aws-rds';
import * as secrets from 'aws-cdk-lib/aws-secretsmanager';
import type { Construct } from 'constructs';
import type { StageSettings } from './stage.js';

export interface DataStackProps extends StackProps {
  readonly settings: StageSettings;
  readonly vpc: ec2.IVpc;
  readonly dbSg: ec2.ISecurityGroup;
  readonly dataKey: kms.IKey;
}

/** Postgres 16 on RDS plus the application secrets. Nothing here is reachable from the internet. */
export class DataStack extends Stack {
  readonly db: rds.DatabaseInstance;
  readonly dbName = 'app';
  readonly appSecrets: Record<'jwt' | 'otpPepper' | 'fieldKey' | 'webhook', secrets.Secret>;

  constructor(scope: Construct, id: string, props: DataStackProps) {
    super(scope, id, props);
    const s = props.settings;

    const params = new rds.ParameterGroup(this, 'Params', {
      engine: rds.DatabaseInstanceEngine.postgres({ version: rds.PostgresEngineVersion.VER_16 }),
      parameters: {
        'rds.force_ssl': '1', // refuse unencrypted connections
        log_min_duration_statement: '1000',
      },
    });

    this.db = new rds.DatabaseInstance(this, 'Postgres', {
      engine: rds.DatabaseInstanceEngine.postgres({ version: rds.PostgresEngineVersion.VER_16 }),
      instanceType: new ec2.InstanceType(s.dbInstance),
      vpc: props.vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PRIVATE_ISOLATED },
      securityGroups: [props.dbSg],
      databaseName: this.dbName,
      // Secrets use the AWS-managed Secrets Manager key: task roles are granted through IAM alone,
      // which keeps the data/app stacks free of cross-stack key-policy edits.
      credentials: rds.Credentials.fromGeneratedSecret('app_owner'),
      storageEncrypted: true,
      storageEncryptionKey: props.dataKey,
      allocatedStorage: 20,
      maxAllocatedStorage: 200,
      multiAz: s.dbMultiAz,
      publiclyAccessible: false,
      backupRetention: Duration.days(s.dbBackupDays),
      deletionProtection: s.dbDeletionProtection,
      removalPolicy: s.dbDeletionProtection ? RemovalPolicy.RETAIN : RemovalPolicy.SNAPSHOT,
      parameterGroup: params,
      cloudwatchLogsExports: ['postgresql'],
      autoMinorVersionUpgrade: true,
      caCertificate: rds.CaCertificate.RDS_CA_RSA2048_G1,
    });

    // Generated by Secrets Manager; never in the repo, CI or CloudFormation templates.
    const gen = (name: string, description: string) =>
      new secrets.Secret(this, name, {
        description,
        generateSecretString: { passwordLength: 64, excludePunctuation: true, includeSpace: false },
      });
    this.appSecrets = {
      jwt: gen('JwtSecret', 'Access-token signing key'),
      otpPepper: gen('OtpPepper', 'Pepper for OTP code hashes'),
      fieldKey: gen('FieldKey', 'Key material for TOTP secret encryption'),
      webhook: gen('CollectionsWebhookSecret', 'Collections provider webhook signing secret (sandbox until a provider is chosen)'),
    };
  }
}
